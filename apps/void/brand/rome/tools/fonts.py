"""fonts.gen.ts: the film's fonts (SIL OFL 1.1; media/fonts/*-OFL.txt) as @font-face rules with the files inline, each
subset to Latin, Greek and the punctuation the film sets (fontTools), so the page carries no more than it draws.

  uv run --with fonttools python -I tools/fonts.py
"""
import base64, io
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

HERE = Path(__file__).resolve().parent.parent
F = HERE / "media/fonts"
# family, weight range, style, file
FACES = [
    ("Cormorant Garamond", "300 700", "normal", "CormorantGaramond-Variable.ttf"),
    ("Cormorant Garamond", "300 700", "italic", "CormorantGaramond-Italic-Variable.ttf"),
    ("EB Garamond", "400 800", "italic", "EBGaramond-Italic-Variable.ttf"),  # the Greek: Cormorant has none
    ("Cinzel", "400 900", "normal", "Cinzel-Variable.ttf"),
    ("Inter", "100 900", "normal", "Inter-Variable.ttf"),
]
UNICODES = "U+0020-007E,U+00A0-00FF,U+0131,U+0152-0153,U+02C6,U+02DA,U+02DC,U+0370-03FF,U+1F00-1FFF,U+2013-2014,U+2018-201E,U+2022,U+2026,U+2032-2033,U+2039-203A,U+2070-209F,U+2160-2188"

rules = []
for family, weight, style, name in FACES:
    font = TTFont(F / name)
    opts = subset.Options()
    opts.layout_features = ["*"]  # keep ligatures, small caps, old-style figures
    opts.name_IDs = ["*"]
    opts.notdef_outline = True
    s = subset.Subsetter(opts)
    s.populate(unicodes=subset.parse_unicodes(UNICODES))
    s.subset(font)
    buf = io.BytesIO()
    font.save(buf)
    b64 = base64.b64encode(buf.getvalue()).decode()
    rules.append(f'@font-face {{ font-family: "{family}"; font-weight: {weight}; font-style: {style}; src: url(data:font/ttf;base64,{b64}) format("truetype"); }}')
    print(f"{name}: {len(buf.getvalue()) // 1024} KB")
(HERE / "fonts.gen.ts").write_text(
    "// Cormorant Garamond, EB Garamond, Cinzel and Inter (SIL OFL 1.1; media/fonts/*-OFL.txt), subset and embedded. Generated by\n"
    "// tools/fonts.py; do not edit.\nexport const FONTS = '" + " ".join(rules) + "';\n")
